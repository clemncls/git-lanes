import { stripVTControlCharacters } from "node:util";

const graphemes = new Intl.Segmenter(undefined, { granularity: "grapheme" });
const sgr = /\x1b\[[0-9;]*m/;
export const MAX_TEXT_LENGTH = 4096;

// Only our own colors may reach the terminal. Keep bidi controls visible rather
// than silently making two different branch names look identical.
export function sanitizeText(value) {
  const input = String(value ?? "");
  const safe = stripVTControlCharacters(input.slice(0, MAX_TEXT_LENGTH))
    .replace(
      /[\u00ad\u061c\u200b\u200e\u200f\u202a-\u202e\u2060-\u2069\ufeff]/gu,
      (character) =>
        `\\u${character.codePointAt(0).toString(16).padStart(4, "0")}`,
    )
    .replace(/[\u0000-\u001f\u007f-\u009f\u2028\u2029]/gu, " ");
  return input.length > MAX_TEXT_LENGTH || safe.length > MAX_TEXT_LENGTH
    ? safe.slice(0, MAX_TEXT_LENGTH - 1) + "…"
    : safe;
}

export function terminalWidth(value) {
  const number = Number(value);
  return Number.isFinite(number) && number > 0
    ? Math.max(40, Math.min(240, Math.floor(number)))
    : 100;
}

function cellWidth(segment) {
  if (/^\p{Mark}+$/u.test(segment)) return 0;
  const point = segment.codePointAt(0);
  const wide =
    point >= 0x1100 &&
    (point <= 0x115f ||
      point === 0x2329 ||
      point === 0x232a ||
      (point >= 0x2e80 && point <= 0xa4cf && point !== 0x303f) ||
      (point >= 0xac00 && point <= 0xd7a3) ||
      (point >= 0xf900 && point <= 0xfaff) ||
      (point >= 0xfe10 && point <= 0xfe19) ||
      (point >= 0xfe30 && point <= 0xfe6f) ||
      (point >= 0xff00 && point <= 0xff60) ||
      (point >= 0xffe0 && point <= 0xffe6) ||
      (point >= 0x20000 && point <= 0x3fffd));
  return wide ||
    /\p{Emoji_Presentation}|\p{Regional_Indicator}|\uFE0F/u.test(segment)
    ? 2
    : 1;
}

export function visibleWidth(text) {
  let width = 0;
  for (const { segment } of graphemes.segment(stripVTControlCharacters(text)))
    width += cellWidth(segment);
  return width;
}

export function clipText(text, width) {
  if (visibleWidth(text) <= width) return text;
  let result = "",
    used = 0;
  for (const { segment } of graphemes.segment(text)) {
    const size = cellWidth(segment);
    if (used + size > width - 1) break;
    result += segment;
    used += size;
  }
  return result + "…";
}

// Receives sanitized text plus trusted SGR colors generated by the renderer.
export function wrapLine(line, width, color = false) {
  if (visibleWidth(line) <= width) return line;
  let result = "",
    column = 0,
    active = "";
  const nextLine = () => {
    result += `${color ? "\x1b[0m" : ""}\n${color ? "\x1b[38;5;245m" : ""}    ↪ ${color ? "\x1b[0m" : ""}${active}`;
    column = 6;
  };
  for (const word of line.match(/(?:\x1b\[[0-9;]*m|[^\s\x1b])+|[ \t]+/gu) ||
    []) {
    if (word.trim() && column > 6 && column + visibleWidth(word) > width - 1)
      nextLine();
    for (const token of word.match(/\x1b\[[0-9;]*m|[^\x1b]+/gu) || []) {
      if (sgr.test(token) && token.startsWith("\x1b")) {
        active = token === "\x1b[0m" ? "" : token;
        result += token;
      } else {
        for (const { segment } of graphemes.segment(token)) {
          const size = cellWidth(segment);
          if (column + size > width - 1) nextLine();
          result += segment;
          column += size;
        }
      }
    }
  }
  return result;
}
